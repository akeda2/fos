#!/usr/bin/env python3
"""Generates kernel/src/arch/x86_64/isr_stubs.S: 256 interrupt entry stubs of 16 bytes each
(so the kernel can compute stub N's address as `isr_0 + 16 * N` and needs no
relocated pointer table) and the common code they jump to.

Each stub makes the stack look the same for every vector: the CPU pushes an error
code only for some exceptions (8, 10-14, 17, 21, 29, 30), so the others push a
dummy 0; then the vector number is pushed. `isr_common` saves every general
register and calls the Rust `interrupt_dispatch(frame)`.

    python3 tools/gen_isr_stubs.py > kernel/src/arch/x86_64/isr_stubs.S

With `--swapgs` (the server kernel, which runs ring 3 code) `isr_common` swaps the GS base on entry from and exit to ring 3
(CS RPL != 0), so user code can never leave its own GS base in the kernel's hands; `isr_common_body` is the entry for code
that has already done the swap itself (the `syscall` stub):

    python3 tools/gen_isr_stubs.py --swapgs > kernel-mf/src/isr_stubs.S
"""

import sys

SWAPGS = "--swapgs" in sys.argv

ERROR_CODE_VECTORS = {8, 10, 11, 12, 13, 14, 17, 21, 29, 30}

print("# Generated by tools/gen_isr_stubs.py" + (" --swapgs" if SWAPGS else "") + ". Do not edit.")
print(".section .text, \"ax\"")
print(".balign 16")
print(".global isr_0")
for vector in range(256):
    print(f"isr_{vector}:")
    if vector not in ERROR_CODE_VECTORS:
        print("    push 0")
    print(f"    push {vector}")
    print("    jmp isr_common")
    print(".balign 16")
print("""
# The frame the Rust side sees (lowest address first): r15..r8, rdi, rsi, rbp, rbx,
# rdx, rcx, rax, vector, error code, then the CPU's own rip, cs, rflags, rsp, ss.
isr_common:""")
if SWAPGS:
    print("""    test byte ptr [rsp + 24], 3      # came from ring 3? then GS is the user's: swap in the kernel's
    jz 1f
    swapgs
1:
.global isr_common_body
isr_common_body:""")
print("""    push rax
    push rcx
    push rdx
    push rbx
    push rbp
    push rsi
    push rdi
    push r8
    push r9
    push r10
    push r11
    push r12
    push r13
    push r14
    push r15
    mov rdi, rsp
    cld
    call interrupt_dispatch
    pop r15
    pop r14
    pop r13
    pop r12
    pop r11
    pop r10
    pop r9
    pop r8
    pop rdi
    pop rsi
    pop rbp
    pop rbx
    pop rdx
    pop rcx
    pop rax
    add rsp, 16""")
if SWAPGS:
    print("""    test byte ptr [rsp + 8], 3       # returning to ring 3: put the user's GS back
    jz 2f
    swapgs
2:""")
print("    iretq")
