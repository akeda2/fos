#!/usr/bin/env python3
"""Turns a Linux console font (PSF1/PSF2, optionally gzipped) into the Rust array
the kernel's framebuffer console draws with.

The font used is console-setup's Lat15-Fixed16 (8x16, 256 glyphs). Its glyphs are NOT
stored in Latin-9 order (only ASCII happens to be at its usual codes): the unicode table
at the end of the file says which glyph draws which character, so the output is
rearranged here into ISO 8859-15 order, the cell values the console uses. Debian's console-setup copyright file
says "All console fonts are public domain by nature", and this one is derived from
the X11 misc-fixed font, which is public domain too. Re-generate with:

    python3 tools/psf_to_rust.py /usr/share/consolefonts/Lat15-Fixed16.psf.gz \
        > kernel/src/font_data.rs
"""

import gzip
import struct
import sys


def load(path):
    data = open(path, "rb").read()
    if data[:2] == b"\x1f\x8b":
        data = gzip.decompress(data)
    if data[:2] == b"\x36\x04":  # PSF1: magic, mode, charsize; 8 pixels wide
        mode, height = data[2], data[3]
        glyphs = 512 if mode & 1 else 256
        return 8, height, glyphs, data[4:], data[4 + glyphs * height:] if mode & 6 else b""
    if data[:4] == b"\x72\xb5\x4a\x86":  # PSF2
        (_, _, header, _, glyphs, bytes_per, height, width) = struct.unpack("<8I", data[:32])[0:8]
        return width, height, glyphs, data[header:], b""
    raise SystemExit("not a PSF font")


def glyph_order(table, glyphs):
    """PSF1 unicode table: per glyph, UCS-2 code points ended by 0xFFFF (0xFFFE starts sequences, ignored)."""
    owners = {}
    index = 0
    for (value,) in struct.iter_unpack("<H", table[: len(table) // 2 * 2]):
        if index >= glyphs:
            break
        if value == 0xFFFF:
            index += 1
        elif value != 0xFFFE:
            owners.setdefault(value, index)
    return owners


def main():
    width, height, glyphs, body, table = load(sys.argv[1])
    assert width == 8 and height == 16, f"expected an 8x16 font, got {width}x{height}"
    print("// Generated by tools/psf_to_rust.py from console-setup's Lat15-Fixed16")
    print("// (public domain: derived from X11 misc-fixed; see that script). Do not edit.")
    print()
    print("pub const FONT_WIDTH: usize = 8;")
    print("pub const FONT_HEIGHT: usize = 16;")
    print()
    print("/// One byte per pixel row, most significant bit leftmost, 256 glyphs.")
    print("pub static FONT: [[u8; 16]; 256] = [")
    owners = glyph_order(table, glyphs)
    for code in range(256):
        index = code
        if code >= 0xa0:
            index = owners[ord(bytes([code]).decode("iso8859-15"))]
        rows = body[index * 16:(index + 1) * 16]
        print("    [" + ", ".join(f"0x{row:02x}" for row in rows) + "],")
    print("];")


if __name__ == "__main__":
    main()
